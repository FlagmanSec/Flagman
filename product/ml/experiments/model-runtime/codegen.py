"""Code generation: a LightGBM model's trees as plain C, for the measurement.

Reads ``Booster.dump_model()`` and writes one C function::

    void flagman_raw_scores(const double *x, double *out);

It adds each tree's leaf value to ``out[class]``, tree by tree in
LightGBM's order (class = tree index modulo the number of classes), so the
sums are LightGBM's raw scores. Each split follows LightGBM's rules
(include/LightGBM/tree.h, v4.7.0, ``NumericalDecision`` and
``CategoricalDecision``):

- numbers: an empty value (NaN) becomes 0 unless the split's missing type
  is NaN; a missing value (NaN, or zero for missing type Zero) goes to the
  default side; otherwise ``value <= threshold`` goes left;
- categories: NaN or a negative value goes right; a value in the split's
  list of categories goes left.

``measure.py`` compiles the result and compares its scores with
LightGBM's. LightGBM has its own C++ generator (``Tree::ToIfElse``, used
by its ``convert_model`` task); this one is written here so that the
measurement needs only Python and a C compiler.
"""

from __future__ import annotations

import json
import sys

HEADER = """#include <math.h>
/* Generated by codegen.py from a LightGBM model: do not edit. */
static const double ZERO = 1.0000000180025095e-35; /* kZeroThreshold = 1e-35f */
static int is_zero(double f) { return f >= -ZERO && f <= ZERO; }
static int left_nan(double f, double t, int dl) { return isnan(f) ? dl : f <= t; }
static int left_zero(double f, double t, int dl) {
    if (isnan(f)) f = 0.0;
    return is_zero(f) ? dl : f <= t;
}
static int left_none(double f, double t) {
    if (isnan(f)) f = 0.0;
    return f <= t;
}
"""


def condition(node: dict) -> str:
    """The C test that sends a value to the left child."""
    value = f"x[{node['split_feature']}]"
    if node["decision_type"] == "==":
        cats = " || ".join(f"(int){value} == {int(c)}" for c in str(node["threshold"]).split("||"))
        return f"(!isnan({value}) && (int){value} >= 0 && ({cats}))"
    threshold, default_left = repr(float(node["threshold"])), int(bool(node["default_left"]))
    if node["missing_type"] == "NaN":
        return f"left_nan({value}, {threshold}, {default_left})"
    if node["missing_type"] == "Zero":
        return f"left_zero({value}, {threshold}, {default_left})"
    return f"left_none({value}, {threshold})"


def tree_code(node: dict, target: int, depth: int) -> list[str]:
    pad = "    " * depth
    if "leaf_value" in node:
        return [f"{pad}out[{target}] += {float(node['leaf_value'])!r};"]
    return ([f"{pad}if ({condition(node)}) {{"]
            + tree_code(node["left_child"], target, depth + 1)
            + [f"{pad}}} else {{"]
            + tree_code(node["right_child"], target, depth + 1)
            + [f"{pad}}}"])


def generate(model: dict) -> str:
    per_iteration = model["num_tree_per_iteration"]
    lines = [HEADER, "void flagman_raw_scores(const double *x, double *out) {"]
    lines += [f"    out[{k}] = 0.0;" for k in range(per_iteration)]
    for tree in model["tree_info"]:
        lines.append(f"    /* tree {tree['tree_index']} */")
        lines += tree_code(tree["tree_structure"], tree["tree_index"] % per_iteration, 1)
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open(sys.argv[1], encoding="utf-8") as file:
        sys.stdout.write(generate(json.load(file)))
